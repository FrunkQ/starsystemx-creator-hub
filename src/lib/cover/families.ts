// TWO MORE ALPHABETS (D-46). Different letters, not the same letters drawn differently.
//
// ============================================================================================
// The owner, 2026-09-06: *"Different fonts - i kinda suggested new font families for different
// look and feel."* Fair. `pixel`, `bold`, `outline` and `wide` are four ways of DRAWING one glyph
// set, so three of them are the same typeface with a treatment on top - which is why picking one
// changes less than a person expects from a control labelled with font names.
//
// So here are two more SETS, which `font.ts` predicted would be data rather than code:
//
//   ROUND    geometric and pointed: circular bowls, a pointed A and M, a single-storey G. Reads
//            softer and more deliberate - a poster face rather than a readout.
//   NARROW   three columns instead of five. Not the base squeezed - squeezing 5 into 3 loses the
//            counters - but its own condensed alphabet, which gives a much tighter rhythm and
//            fits half again as many letters on a line. A data plate rather than a title card.
//
// PUNCTUATION FALLS THROUGH to the base set on purpose: a hyphen is a hyphen at any width, and
// forty more glyphs that nobody could tell apart is forty more chances to draw one wrong.
// Anything a family does not define is taken from `GLYPHS` in `font.ts`.
//
// Each glyph is seven rows; `#` is ink. A family's rows may be any width - the advance is measured
// from the glyph itself - which is the whole reason NARROW works without touching the renderer.
// ============================================================================================

